/** 生成教学视频搜索链接（B站 / YouTube） */
export function searchLinks(keyword: string) {
  return {
    bilibili: `https://search.bilibili.com/all?keyword=${encodeURIComponent(keyword)}`,
    youtube: `https://www.youtube.com/results?search_query=${encodeURIComponent(keyword)}`
  }
}

/** 解析视频链接为可嵌入的 iframe 地址；不支持则返回 null */
export function toEmbedUrl(url: string): string | null {
  const u = url.trim()
  // Bilibili: BV 号
  const bv = u.match(/BV[a-zA-Z0-9]+/)
  if (bv) return `https://player.bilibili.com/player.html?bvid=${bv[0]}&autoplay=0&high_quality=1`
  // YouTube
  const yt = u.match(/(?:youtube\.com\/watch\?v=|youtu\.be\/|youtube\.com\/embed\/)([\w-]{11})/)
  if (yt) return `https://www.youtube.com/embed/${yt[1]}`
  return null
}
